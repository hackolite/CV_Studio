def _gpu_mem_str(device: torch.device) -> str:
    """Retourne la mémoire GPU réservée formatée (ex: '3.2G'), ou '' sur CPU."""
    if device.type != "cuda":
        return ""
    try:
        mem = torch.cuda.memory_reserved(device) / 1e9
        return f"{mem:.2f}G"
    except Exception:
        return ""


def _print_epoch_header() -> None:
    """Imprime l'en-tête de tableau style Ultralytics."""
    print(
        f"\n{'':>10s}{'gpu_mem':>10s}"
        f"{'box_loss':>10s}{'cls_loss':>10s}{'obj_loss':>10s}"
        f"{'val_box':>10s}{'val_cls':>10s}{'val_obj':>10s}"
        f"{'P':>8s}{'R':>8s}{'mAP50':>9s}{'lr':>12s}",
        flush=True,
    )


def run_epoch(
    model:        nn.Module,
    loader:       DataLoader,
    optimizer:    torch.optim.Optimizer,
    scaler:       torch.amp.GradScaler,
    cfg:          Config,
    device:       torch.device,
    writer=None,
    global_step:  int = 0,
    train:        bool = True,
    epoch:        int = 0,
    total_epochs: int = 0,
) -> tuple[dict[str, float], int]:
    model.train(train)
    totals:    dict[str, float] = {}
    n_batches: int = 0
    ctx = torch.amp.autocast("cuda", enabled=(device.type == "cuda"))

    phase = "train" if train else "val"
    desc  = (f"Epoch {epoch}/{total_epochs} [{phase}]"
             if total_epochs > 0 else phase)

    with tqdm(loader, desc=desc, leave=False) as pbar:
        for step, (imgs, cls_t, obj_t, box_t) in enumerate(pbar):
            imgs  = imgs.to(device,  non_blocking=True)
            cls_t = cls_t.to(device, non_blocking=True)
            obj_t = obj_t.to(device, non_blocking=True)
            box_t = box_t.to(device, non_blocking=True)

            with ctx:
                cls_p, obj_p, box_p = model(imgs)
                loss, details = compute_loss(
                    cls_p, obj_p, box_p, cls_t, obj_t, box_t, cfg, device
                )

            if train:
                optimizer.zero_grad(set_to_none=True)
                scaler.scale(loss).backward()
                scaler.unscale_(optimizer)
                nn.utils.clip_grad_norm_(model.parameters(), cfg.grad_clip)
                scaler.step(optimizer)
                scaler.update()

                if writer:
                    for k, v in details.items():
                        writer.add_scalar(k, v, global_step)
                global_step += 1

            for k, v in details.items():
                totals[k] = totals.get(k, 0.0) + v
            n_batches += 1
            avg_box = totals.get("loss/box", 0.0) / n_batches
            avg_cls = totals.get("loss/cls", 0.0) / n_batches
            avg_obj = totals.get("loss/obj", 0.0) / n_batches
            mem = _gpu_mem_str(device)
            postfix: dict = {
                "box": f"{avg_box:.4f}",
                "cls": f"{avg_cls:.4f}",
                "obj": f"{avg_obj:.4f}",
            }
            if mem:
                postfix = {"mem": mem, **postfix}
            pbar.set_postfix(postfix)

            if cfg.max_steps is not None and step >= cfg.max_steps - 1:
                log.debug("max_steps=%d atteint.", cfg.max_steps)
                break

    averages = {k: v / n_batches for k, v in totals.items()}
    return averages, global_step


def train(cfg: Config = CFG) -> None:
    set_seed(cfg.seed)
    device = cfg.device
    log.info("Device : %s", device)

    if not (Path(cfg.img_dir).exists() and Path(cfg.ann_path).exists()):
        log.error("Dataset introuvable : %s / %s", cfg.img_dir, cfg.ann_path)
        return

    transform = T.Compose([
        T.Resize((cfg.img_size, cfg.img_size)),
        T.ColorJitter(brightness=0.2, contrast=0.2, saturation=0.2),
        T.ToTensor(),
    ])

    full_dataset = CocoDetection(cfg.img_dir, cfg.ann_path, transform=transform)
    n_val   = max(1, int(len(full_dataset) * cfg.val_split))
    n_train = len(full_dataset) - n_val
    train_ds, val_ds = random_split(
        full_dataset, [n_train, n_val],
        generator=torch.Generator().manual_seed(cfg.seed),
    )
    log.info("Dataset : %d train, %d val", n_train, n_val)

    # Mapping dynamique — ignore coco_valid_ids si vide, sinon le valide
    if cfg.coco_valid_ids:
        label_map  = cfg.label_map
        num_classes = cfg.num_classes
    else:
        label_map, num_classes = build_label_map_from_annotations(cfg.ann_path)
        if num_classes != cfg.num_classes:
            log.warning(
                "num_classes config (%d) ≠ annotations (%d) — on utilise %d",
                cfg.num_classes, num_classes, num_classes,
            )

    collate      = make_collate(cfg, label_map)
    n_workers    = min(4, os.cpu_count() or 1)
    train_loader = DataLoader(
        train_ds, batch_size=cfg.batch_size, shuffle=True,
        collate_fn=collate, num_workers=n_workers,
        pin_memory=(device.type == "cuda"), persistent_workers=True,
    )
    val_loader = DataLoader(
        val_ds, batch_size=cfg.batch_size, shuffle=False,
        collate_fn=collate, num_workers=max(1, n_workers // 2),
        pin_memory=(device.type == "cuda"), persistent_workers=True,
    )

    model = NanoDetLite(cfg.num_classes).to(device)
    log.info("Paramètres : %.2f M",
             sum(p.numel() for p in model.parameters()) / 1e6)

    optimizer   = torch.optim.AdamW(
        model.parameters(), lr=cfg.lr, weight_decay=cfg.weight_decay
    )
    total_steps = cfg.epochs * len(train_loader)
    scheduler   = torch.optim.lr_scheduler.CosineAnnealingLR(
        optimizer, T_max=total_steps, eta_min=cfg.lr * 1e-2
    )
    scaler   = torch.amp.GradScaler("cuda", enabled=(device.type == "cuda"))
    ckpt_mgr = CheckpointManager(cfg.ckpt_dir)
    writer   = SummaryWriter(LOG_DIR / "tb") if _TB_AVAILABLE else None

    start_epoch = 0
    global_step = 0
    if cfg.resume:
        start_epoch = ckpt_mgr.load(cfg.resume, model, optimizer, scheduler)

    best_map50 = 0.0
    _print_epoch_header()

    for epoch in range(start_epoch, cfg.epochs):

        train_metrics, global_step = run_epoch(
            model, train_loader, optimizer, scaler, cfg, device,
            writer=writer, global_step=global_step, train=True,
            epoch=epoch + 1, total_epochs=cfg.epochs,
        )
        scheduler.step()

        with torch.no_grad():
            val_metrics, _ = run_epoch(
                model, val_loader, optimizer, scaler, cfg, device,
                writer=writer, global_step=global_step, train=False,
                epoch=epoch + 1, total_epochs=cfg.epochs,
            )

        # mAP + P/R/F1 sur un sous-ensemble pour limiter le temps de calcul
        map50, ap_dict, det_metrics = evaluate_map(
            model, val_loader, cfg, device, max_images=500
        )

        # ── Ligne de tableau style Ultralytics ──────────────────────────────
        lr_now  = optimizer.param_groups[0]["lr"]
        mem_str = _gpu_mem_str(device)
        epoch_str = f"{epoch + 1}/{cfg.epochs}"
        print(
            f"{epoch_str:>10s}{mem_str:>10s}"
            f"{train_metrics.get('loss/box', 0):>10.4f}"
            f"{train_metrics.get('loss/cls', 0):>10.4f}"
            f"{train_metrics.get('loss/obj', 0):>10.4f}"
            f"{val_metrics.get('loss/box', 0):>10.4f}"
            f"{val_metrics.get('loss/cls', 0):>10.4f}"
            f"{val_metrics.get('loss/obj', 0):>10.4f}"
            f"{det_metrics['metrics/precision']:>8.3f}"
            f"{det_metrics['metrics/recall']:>8.3f}"
            f"{map50:>9.4f}"
            f"{lr_now:>12.2e}",
            flush=True,
        )

        # ── Tableau par classe style Ultralytics ────────────────────────────
        valid_aps = [(c, v) for c, v in ap_dict.items() if not math.isnan(v)]
        if valid_aps:
            print(
                f"\n{'':>18s}{'Class':>10s}{'AP50':>10s}",
                flush=True,
            )
            for cls_id, ap in sorted(valid_aps, key=lambda x: -x[1])[:10]:
                print(f"{'':>18s}{f'cls{cls_id}':>10s}{ap:>10.3f}", flush=True)
            mean_ap = sum(v for _, v in valid_aps) / len(valid_aps)
            print(f"{'':>18s}{'all':>10s}{mean_ap:>10.3f}\n", flush=True)

        if writer:
            for k, v in val_metrics.items():
                writer.add_scalar("val/" + k.split("/")[1], v, epoch)
            writer.add_scalar("metrics/mAP50", map50, epoch)
            for k, v in det_metrics.items():
                writer.add_scalar(k, v, epoch)
            writer.add_scalar("lr", lr_now, epoch)

        if (epoch + 1) % cfg.save_every == 0:
            ckpt_mgr.save(
                epoch + 1, model, optimizer, scheduler,
                {**val_metrics, "mAP50": map50, **det_metrics}, cfg,
            )

        if map50 > best_map50:
            best_map50 = map50
            best_path  = Path(cfg.ckpt_dir) / "best.pt"
            torch.save(model.state_dict(), best_path)
            print(f"  ✦ best model saved  mAP50={best_map50:.4f}", flush=True)

    if writer:
        writer.close()
    print(f"\n✔ ENTRAÎNEMENT TERMINÉ  best mAP50={best_map50:.4f}", flush=True)


