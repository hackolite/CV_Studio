# Représentation stockée dans box_t :
#   [tx, ty] : offset de cellule ∈ [0, 1]   (= sigmoid de la sortie brute)
#   [tw, th] : taille relative à l'image ∈ [0, wh_scale]
#              (= sigmoid(raw) * wh_scale)
#
# Au décodage : même formule — pas de exp(), pas de mismatch.
# wh_scale=2.0 signifie qu'on peut prédire des boîtes allant jusqu'à
# 2× la taille de l'image, ce qui couvre tous les cas COCO.

def encode_box(cx_pixel: float, cy_pixel: float,
               w: float, h: float,
               ix: int, iy: int,
               stride: float, img_size: int,
               wh_scale: float) -> tuple[float, float, float, float]:
    """
    Encode une boîte en cibles pour sigmoid-only box head.
    Retourne (tx, ty, tw, th) directement stockés dans box_t.
    """
    gx = cx_pixel / stride
    gy = cy_pixel / stride
    tx = gx - ix                         # offset x ∈ [0, 1]
    ty = gy - iy                         # offset y ∈ [0, 1]
    tw = (w / img_size) / wh_scale       # ∈ [0, 1] pour sigmoid inverse
    th = (h / img_size) / wh_scale
    return tx, ty, tw, th


def decode_box(raw: torch.Tensor,
               grid_x: torch.Tensor,
               grid_y: torch.Tensor,
               stride: float,
               img_size: int,
               wh_scale: float) -> tuple[torch.Tensor, ...]:
    """
    Décode les sorties brutes box_p en coordonnées pixel absolues cx,cy,w,h.
    Tout est en sigmoid — aucun exp().
    """
    pred_cx = (torch.sigmoid(raw[:, 0]) + grid_x) * stride
    pred_cy = (torch.sigmoid(raw[:, 1]) + grid_y) * stride
    pred_w  = torch.sigmoid(raw[:, 2]) * wh_scale * img_size
    pred_h  = torch.sigmoid(raw[:, 3]) * wh_scale * img_size
    return pred_cx, pred_cy, pred_w, pred_h


