def export_onnx(
    model:        Optional[nn.Module] = None,
    cfg:          Config              = CFG,
    weights_path: Optional[str]       = None,
) -> None:
    """Exporte et vérifie la cohérence PyTorch / OnnxRuntime."""
    if model is None:
        model = NanoDetLite(cfg.num_classes)
        if weights_path:
            ckpt  = torch.load(weights_path, map_location="cpu")
            state = ckpt.get("model", ckpt)
            model.load_state_dict(state)
            log.info("Poids chargés depuis %s", weights_path)

    model.eval().cpu()
    dummy = torch.randn(1, 3, cfg.img_size, cfg.img_size)

    torch.onnx.export(
        model, dummy, cfg.onnx_path,
        input_names=["input"],
        output_names=["cls", "obj", "box"],
        opset_version=cfg.opset,
        dynamic_axes={"input": {0: "batch"}},
        do_constant_folding=False,
    )
    log.info("ONNX exporté : %s", cfg.onnx_path)

    # Garantit un fichier ONNX unique (sans données externes séparées)
    try:
        import onnx as _onnx_mod
        _proto = _onnx_mod.load(cfg.onnx_path)
        _onnx_mod.save_model(
            _proto, cfg.onnx_path,
            save_as_external_data=False,
        )
        log.info("ONNX sauvegardé en fichier unique : %s", cfg.onnx_path)
    except ImportError:
        log.warning("onnx non installé — impossble de garantir le fichier unique.")

    try:
        import onnx
        import onnxruntime as ort

        onnx.checker.check_model(onnx.load(cfg.onnx_path))
        sess     = ort.InferenceSession(cfg.onnx_path, providers=["CPUExecutionProvider"])
        ort_outs = sess.run(None, {"input": dummy.numpy()})

        with torch.no_grad():
            pt_outs = [t.numpy() for t in model(dummy)]

        for i, (pt, ort_out) in enumerate(zip(pt_outs, ort_outs)):
            max_diff = np.abs(pt - ort_out).max()
            log.info("Output[%d] max_diff PyTorch/ONNX = %.2e", i, max_diff)
            assert max_diff < 1e-4, f"Écart trop grand sur output[{i}] : {max_diff}"

        log.info("✔ ONNX vérifié (cohérence PyTorch / OnnxRuntime OK)")

    except ImportError:
        log.warning("onnxruntime/onnx non installé — vérification ignorée.")
    except AssertionError as e:
        log.error("Vérification ONNX échouée : %s", e)
        raise


