def _iou_single(box_a: torch.Tensor, box_b: torch.Tensor) -> torch.Tensor:
    """IoU entre deux tenseurs de boîtes [N,4] et [M,4]. Retourne [N,M]."""
    return box_iou(box_a, box_b)


def compute_precision_recall(
    pred_boxes:   torch.Tensor,   # [N, 4] x1y1x2y2
    pred_scores:  torch.Tensor,   # [N]
    pred_labels:  torch.Tensor,   # [N]
    gt_boxes:     torch.Tensor,   # [M, 4]
    gt_labels:    torch.Tensor,   # [M]
    num_classes:  int,
    iou_threshold: float = 0.5,
) -> dict[int, tuple[np.ndarray, np.ndarray]]:
    """
    Calcule les courbes précision/rappel par classe pour une image.

    Retourne un dict {class_id: (precisions, recalls)} où chaque élément
    est un ndarray trié par score décroissant.
    """
    results: dict[int, tuple[np.ndarray, np.ndarray]] = {}

    for cls_id in range(num_classes):
        pred_mask = pred_labels == cls_id
        gt_mask   = gt_labels   == cls_id

        p_boxes  = pred_boxes[pred_mask]
        p_scores = pred_scores[pred_mask]
        g_boxes  = gt_boxes[gt_mask]

        n_gt = g_boxes.shape[0]
        n_p  = p_boxes.shape[0]

        if n_gt == 0 and n_p == 0:
            continue

        if n_p == 0:
            results[cls_id] = (np.array([0.0]), np.array([0.0]))
            continue

        # Tri par score décroissant
        order    = p_scores.argsort(descending=True)
        p_boxes  = p_boxes[order]
        p_scores = p_scores[order]

        tp = np.zeros(n_p, dtype=np.float32)
        fp = np.zeros(n_p, dtype=np.float32)
        matched = np.zeros(n_gt, dtype=bool)

        if n_gt > 0:
            ious = box_iou(p_boxes, g_boxes).cpu().numpy()   # [n_p, n_gt]
            for i in range(n_p):
                best_iou  = -1.0
                best_gt   = -1
                for j in range(n_gt):
                    if not matched[j] and ious[i, j] > best_iou:
                        best_iou = ious[i, j]
                        best_gt  = j
                if best_iou >= iou_threshold:
                    tp[i] = 1.0
                    matched[best_gt] = True
                else:
                    fp[i] = 1.0
        else:
            fp[:] = 1.0

        cum_tp = np.cumsum(tp)
        cum_fp = np.cumsum(fp)
        recalls    = cum_tp / (n_gt + 1e-9)
        precisions = cum_tp / (cum_tp + cum_fp + 1e-9)

        results[cls_id] = (precisions, recalls)

    return results


def _ap_from_pr(precisions: np.ndarray, recalls: np.ndarray) -> float:
    """
    Calcule l'AP par interpolation 11 points (style VOC 2010).
    Plus robuste que l'AUC trapézoïdal pour de petits datasets.
    """
    ap = 0.0
    for thr in np.linspace(0, 1, 11):
        mask = recalls >= thr
        ap  += precisions[mask].max() if mask.any() else 0.0
    return ap / 11.0


def per_class_ap(
    all_pred_boxes:  list[torch.Tensor],   # par image
    all_pred_scores: list[torch.Tensor],
    all_pred_labels: list[torch.Tensor],
    all_gt_boxes:    list[torch.Tensor],
    all_gt_labels:   list[torch.Tensor],
    num_classes: int,
    iou_threshold: float = 0.5,
) -> dict[int, float]:
    """
    Calcule l'AP@iou_threshold pour chaque classe sur l'ensemble du dataset.

    Stratégie : accumulation de tous les TP/FP sur toutes les images,
    puis courbe P/R globale (Pascal VOC style).
    """
    # Accumulateurs par classe : liste de (score, is_tp)
    class_preds: dict[int, list[tuple[float, int]]] = defaultdict(list)
    class_n_gt:  dict[int, int]                     = defaultdict(int)

    for p_boxes, p_scores, p_labels, g_boxes, g_labels in zip(
        all_pred_boxes, all_pred_scores, all_pred_labels,
        all_gt_boxes,   all_gt_labels,
    ):
        # Compter les GT par classe
        for cls_id in g_labels.tolist():
            class_n_gt[int(cls_id)] += 1

        for cls_id in range(num_classes):
            pred_mask = p_labels == cls_id
            gt_mask   = g_labels == cls_id

            p_b = p_boxes[pred_mask]
            p_s = p_scores[pred_mask]
            g_b = g_boxes[gt_mask]

            if p_b.shape[0] == 0:
                continue

            order = p_s.argsort(descending=True)
            p_b   = p_b[order]
            p_s   = p_s[order]

            matched = np.zeros(g_b.shape[0], dtype=bool)

            if g_b.shape[0] > 0:
                ious = box_iou(p_b, g_b).cpu().numpy()
                for i in range(p_b.shape[0]):
                    best_iou, best_gt = -1.0, -1
                    for j in range(g_b.shape[0]):
                        if not matched[j] and ious[i, j] > best_iou:
                            best_iou, best_gt = ious[i, j], j
                    is_tp = int(best_iou >= iou_threshold)
                    if is_tp:
                        matched[best_gt] = True
                    class_preds[cls_id].append((p_s[i].item(), is_tp))
            else:
                for i in range(p_b.shape[0]):
                    class_preds[cls_id].append((p_s[i].item(), 0))

    ap_per_class: dict[int, float] = {}
    for cls_id in range(num_classes):
        n_gt = class_n_gt.get(cls_id, 0)
        if n_gt == 0:
            ap_per_class[cls_id] = float("nan")
            continue

        preds = sorted(class_preds.get(cls_id, []), key=lambda x: -x[0])
        if not preds:
            ap_per_class[cls_id] = 0.0
            continue

        tp_arr = np.array([p[1] for p in preds], dtype=np.float32)
        cum_tp = np.cumsum(tp_arr)
        cum_fp = np.cumsum(1 - tp_arr)
        recalls    = cum_tp / (n_gt + 1e-9)
        precisions = cum_tp / (cum_tp + cum_fp + 1e-9)
        ap_per_class[cls_id] = _ap_from_pr(precisions, recalls)

    return ap_per_class


def compute_map_50(
    all_pred_boxes:  list[torch.Tensor],
    all_pred_scores: list[torch.Tensor],
    all_pred_labels: list[torch.Tensor],
    all_gt_boxes:    list[torch.Tensor],
    all_gt_labels:   list[torch.Tensor],
    num_classes: int,
    iou_threshold: float = 0.5,
) -> tuple[float, dict[int, float]]:
    """
    Point d'entrée principal pour l'évaluation.

    Retourne (mAP@0.5, {class_id: AP}) où mAP est la moyenne sur
    les classes qui ont au moins un GT (NaN exclus).
    """
    ap_dict = per_class_ap(
        all_pred_boxes, all_pred_scores, all_pred_labels,
        all_gt_boxes,   all_gt_labels,
        num_classes,    iou_threshold,
    )
    valid_aps = [v for v in ap_dict.values() if not math.isnan(v)]
    map50 = float(np.mean(valid_aps)) if valid_aps else 0.0
    return map50, ap_dict


def compute_map_coco(
    all_pred_boxes:  list[torch.Tensor],
    all_pred_scores: list[torch.Tensor],
    all_pred_labels: list[torch.Tensor],
    all_gt_boxes:    list[torch.Tensor],
    all_gt_labels:   list[torch.Tensor],
) -> Optional[dict[str, float]]:
    """
    mAP COCO strict via pycocotools (mAP@[.5:.95], AP50, AP75, APs/APm/APl).

    Retourne un dict de métriques, ou None si pycocotools n'est pas installé.
    Utiliser en évaluation finale ; trop lent pour chaque epoch d'entraînement.

    Installation : pip install pycocotools
    """
    try:
        from pycocotools.coco import COCO
        from pycocotools.cocoeval import COCOeval
    except ImportError:
        log.warning(
            "pycocotools non installé — mAP COCO strict ignoré. "
            "pip install pycocotools pour l'activer."
        )
        return None

    # Construction des structures COCO in-memory
    gt_coco: dict = {"images": [], "annotations": [], "categories": []}
    dt_list: list = []
    ann_id = 1

    # Catégories fictives (une par index de classe)
    seen_cats: set[int] = set()
    for g_labels in all_gt_labels:
        for c in g_labels.tolist():
            seen_cats.add(int(c))
    gt_coco["categories"] = [{"id": c, "name": str(c)} for c in sorted(seen_cats)]

    for img_id, (p_boxes, p_scores, p_labels, g_boxes, g_labels) in enumerate(zip(
        all_pred_boxes, all_pred_scores, all_pred_labels,
        all_gt_boxes,   all_gt_labels,
    )):
        gt_coco["images"].append({"id": img_id})

        for box, label in zip(g_boxes.tolist(), g_labels.tolist()):
            x1, y1, x2, y2 = box
            gt_coco["annotations"].append({
                "id": ann_id, "image_id": img_id,
                "category_id": int(label),
                "bbox": [x1, y1, x2 - x1, y2 - y1],
                "area": max(0.0, (x2 - x1) * (y2 - y1)),
                "iscrowd": 0,
            })
            ann_id += 1

        for box, score, label in zip(p_boxes.tolist(), p_scores.tolist(), p_labels.tolist()):
            x1, y1, x2, y2 = box
            dt_list.append({
                "image_id": img_id,
                "category_id": int(label),
                "bbox": [x1, y1, x2 - x1, y2 - y1],
                "score": float(score),
            })

    if not dt_list:
        return {"coco/mAP": 0.0, "coco/AP50": 0.0, "coco/AP75": 0.0}

    import tempfile, json
    with tempfile.NamedTemporaryFile(mode="w", suffix=".json", delete=False) as f:
        json.dump(gt_coco, f)
        gt_path = f.name

    coco_gt = COCO(gt_path)
    coco_dt = coco_gt.loadRes(dt_list)
    ev = COCOeval(coco_gt, coco_dt, "bbox")
    ev.evaluate()
    ev.accumulate()
    ev.summarize()

    return {
        "coco/mAP":    float(ev.stats[0]),   # mAP@[.5:.95]
        "coco/AP50":   float(ev.stats[1]),   # AP@0.5
        "coco/AP75":   float(ev.stats[2]),   # AP@0.75
        "coco/APs":    float(ev.stats[3]),   # AP small
        "coco/APm":    float(ev.stats[4]),   # AP medium
        "coco/APl":    float(ev.stats[5]),   # AP large
    }


def compute_detection_metrics(
    all_pred_boxes:  list[torch.Tensor],
    all_pred_scores: list[torch.Tensor],
    all_pred_labels: list[torch.Tensor],
    all_gt_boxes:    list[torch.Tensor],
    all_gt_labels:   list[torch.Tensor],
    iou_threshold:   float = 0.5,
) -> dict[str, float]:
    """
    Calcule Precision, Recall et F1 globaux (toutes classes confondues)
    à partir des listes d'accumulateurs déjà construites par evaluate_map.

    Matching strict : une prédiction est TP seulement si
      - IoU ≥ iou_threshold avec un GT non encore matché
      - la classe prédite correspond à la classe GT

    Les prédictions sont triées par score décroissant avant matching
    (conforme au protocole Pascal VOC).
    """
    total_tp = 0
    total_fp = 0
    total_fn = 0

    for p_boxes, p_scores, p_labels, g_boxes, g_labels in zip(
        all_pred_boxes, all_pred_scores, all_pred_labels,
        all_gt_boxes,   all_gt_labels,
    ):
        n_gt = g_boxes.shape[0]
        n_p  = p_boxes.shape[0]

        if n_p == 0:
            total_fn += n_gt
            continue

        if n_gt == 0:
            total_fp += n_p
            continue

        # Tri par score décroissant pour un matching greedy cohérent
        order   = p_scores.argsort(descending=True)
        p_boxes  = p_boxes[order]
        p_labels = p_labels[order]

        ious    = box_iou(p_boxes, g_boxes).cpu()   # [n_p, n_gt]
        matched = torch.zeros(n_gt, dtype=torch.bool)

        for i in range(n_p):
            # Parmi les GT non matchés de la même classe, trouver le meilleur IoU
            same_class = (p_labels[i] == g_labels)        # [n_gt]
            candidates = same_class & ~matched             # [n_gt]

            if not candidates.any():
                total_fp += 1
                continue

            iou_row            = ious[i].clone()
            iou_row[~candidates] = -1.0
            best_iou, best_j   = iou_row.max(dim=0)

            if best_iou >= iou_threshold:
                total_tp        += 1
                matched[best_j]  = True
            else:
                total_fp += 1

        total_fn += int((~matched).sum().item())

    precision = total_tp / (total_tp + total_fp + 1e-9)
    recall    = total_tp / (total_tp + total_fn + 1e-9)
    f1        = 2 * precision * recall / (precision + recall + 1e-9)

    return {
        "metrics/precision": float(precision),
        "metrics/recall":    float(recall),
        "metrics/f1":        float(f1),
    }


@torch.no_grad()
def evaluate_map(
    model:      nn.Module,
    loader:     DataLoader,
    cfg:        Config,
    device:     torch.device,
    max_images: Optional[int] = None,
) -> tuple[float, dict[int, float]]:
    """
    Lance l'inférence sur `loader` et calcule mAP@cfg.map_iou_threshold.

    `max_images` limite le nombre d'images évaluées (utile pendant l'entraînement).
    Retourne (mAP50, per_class_AP).
    """
    model.eval()
    all_pred_boxes:  list[torch.Tensor] = []
    all_pred_scores: list[torch.Tensor] = []
    all_pred_labels: list[torch.Tensor] = []
    all_gt_boxes:    list[torch.Tensor] = []
    all_gt_labels:   list[torch.Tensor] = []

    n_images = 0
    stride   = cfg.img_size / cfg.feature_size

    for imgs, cls_t, obj_t, box_t in tqdm(loader, desc="mAP eval", leave=False):
        imgs = imgs.to(device, non_blocking=True)
        cls_p, obj_p, box_p = model(imgs)

        B, _, H, W = cls_p.shape

        # Reconstruire les GT à partir des box_t pour éviter de stocker les anns
        gy_grid, gx_grid = torch.meshgrid(
            torch.arange(H, dtype=torch.float32),
            torch.arange(W, dtype=torch.float32),
            indexing="ij",
        )

        for b in range(B):
            # ---- Prédictions — tout reste sur GPU jusqu'après NMS ----
            result = decode(cls_p[b:b+1], obj_p[b:b+1], box_p[b:b+1], cfg)
            if result is not None:
                boxes, scores, labels = result
                keep_idx = nms(boxes, scores, cfg.nms_iou_threshold)
                # Transfer CPU unique, après NMS (N détections << H×W)
                all_pred_boxes.append(boxes[keep_idx].cpu())
                all_pred_scores.append(scores[keep_idx].cpu())
                all_pred_labels.append(labels[keep_idx].cpu())
            else:
                all_pred_boxes.append(torch.zeros((0, 4)))
                all_pred_scores.append(torch.zeros(0))
                all_pred_labels.append(torch.zeros(0, dtype=torch.long))

            # ---- Ground truth reconstruit depuis box_t / cls_t ----
            pos_mask = (obj_t[b, 0] > 0)   # [H, W]
            pos_iy, pos_ix = pos_mask.nonzero(as_tuple=True)

            if pos_iy.numel() > 0:
                raw_box = box_t[b, :, pos_iy, pos_ix].T   # [N, 4]
                # Inverser encode_box : tx,ty ∈ [0,1] ; tw,th ∈ [0,1]
                cx = (raw_box[:, 0] + pos_ix.float()) * stride
                cy = (raw_box[:, 1] + pos_iy.float()) * stride
                w  = raw_box[:, 2] * cfg.wh_scale * cfg.img_size
                h  = raw_box[:, 3] * cfg.wh_scale * cfg.img_size
                gt_x1 = cx - w / 2
                gt_y1 = cy - h / 2
                gt_x2 = cx + w / 2
                gt_y2 = cy + h / 2
                gt_boxes_b = torch.stack([gt_x1, gt_y1, gt_x2, gt_y2], dim=1)

                # Label : argmax de cls_t sur les cellules positives
                gt_labels_b = cls_t[b, :, pos_iy, pos_ix].argmax(dim=0)

                all_gt_boxes.append(gt_boxes_b)
                all_gt_labels.append(gt_labels_b)
            else:
                all_gt_boxes.append(torch.zeros((0, 4)))
                all_gt_labels.append(torch.zeros(0, dtype=torch.long))

            n_images += 1
            if max_images is not None and n_images >= max_images:
                break

        if max_images is not None and n_images >= max_images:
            break

    map50, ap_dict = compute_map_50(
        all_pred_boxes, all_pred_scores, all_pred_labels,
        all_gt_boxes,   all_gt_labels,
        cfg.num_classes, cfg.map_iou_threshold,
    )
    # P/R/F1 dérivés des mêmes accumulateurs — pas de second parcours
    det_metrics = compute_detection_metrics(
        all_pred_boxes, all_pred_scores, all_pred_labels,
        all_gt_boxes,   all_gt_labels,
        iou_threshold=cfg.map_iou_threshold,
    )
    return map50, ap_dict, det_metrics


