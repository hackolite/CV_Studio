class ConvBnRelu(nn.Sequential):
    def __init__(self, in_ch: int, out_ch: int, kernel: int = 3,
                 stride: int = 1, padding: int = 1) -> None:
        super().__init__(
            nn.Conv2d(in_ch, out_ch, kernel, stride, padding, bias=False),
            nn.BatchNorm2d(out_ch),
            nn.ReLU(inplace=True),
        )


class Backbones(nn.Module):
    """4 convolutions stride-2 → stride global 16."""
    def __init__(self) -> None:
        super().__init__()
        self.net = nn.Sequential(
            ConvBnRelu(3,   16,  stride=2),
            ConvBnRelu(16,  32,  stride=2),
            ConvBnRelu(32,  64,  stride=2),
            ConvBnRelu(64, 128,  stride=2),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.net(x)

class DWConv(nn.Module):
    """Depthwise separable convolution block (MobileNet style)."""
    def __init__(self, in_ch: int, out_ch: int, stride: int = 1):
        super().__init__()

        self.depthwise = nn.Conv2d(
            in_ch, in_ch,
            kernel_size=3,
            stride=stride,
            padding=1,
            groups=in_ch,
            bias=False
        )

        self.pointwise = nn.Conv2d(
            in_ch, out_ch,
            kernel_size=1,
            stride=1,
            bias=False
        )

        self.bn = nn.BatchNorm2d(out_ch)
        self.act = nn.ReLU(inplace=True)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x = self.depthwise(x)
        x = self.pointwise(x)
        x = self.bn(x)
        return self.act(x)


class Backbone(nn.Module):
    """
    Backbone lightweight type MobileNetV1-like :
    - depthwise separable convolutions
    - stride total = 16
    - plus robuste que Conv standard à taille égale
    """
    def __init__(self) -> None:
        super().__init__()

        self.net = nn.Sequential(
            DWConv(3,   16, stride=2),   # 320 -> 160
            DWConv(16,  32, stride=2),   # 160 -> 80
            DWConv(32,  64, stride=2),   # 80  -> 40
            DWConv(64, 128, stride=2),   # 40  -> 20
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.net(x)
class Head(nn.Module):
    """Tête single-scale : cls / objectness / box."""
    def __init__(self, num_classes: int) -> None:
        super().__init__()
        self.shared = nn.Conv2d(128, 128, 3, padding=1)
        self.cls    = nn.Conv2d(128, num_classes, 1)
        self.obj    = nn.Conv2d(128, 1, 1)
        self.box    = nn.Conv2d(128, 4, 1)
        self._init_biases(num_classes)

    def _init_biases(self, num_classes: int) -> None:
        prior_prob = 0.01
        bias_value = -math.log((1 - prior_prob) / prior_prob)
        nn.init.constant_(self.cls.bias, bias_value)
        nn.init.constant_(self.obj.bias, bias_value)

    def forward(self, x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        x = F.relu(self.shared(x), inplace=True)
        return self.cls(x), self.obj(x), self.box(x)


class NanoDetLite(nn.Module):
    def __init__(self, num_classes: int = 80) -> None:
        super().__init__()
        self.backbone = Backbone()
        self.head     = Head(num_classes)

    def forward(self, x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        return self.head(self.backbone(x))


def build_label_map_from_annotations(ann_path: str) -> tuple[dict[int, int], int]:
    """
    Construit dynamiquement le mapping category_id → index continu
    à partir du fichier d'annotations COCO.

    Garantit la stabilité du mapping quel que soit le subset utilisé,
    contrairement à un mapping hardcodé qui peut silencieusement dériver
    sur des subsets COCO personnalisés.

    Retourne (label_map, num_classes).
    """
    import json
    with open(ann_path, "r") as f:
        data = json.load(f)
    # Tri par id pour garantir un ordre déterministe
    cats = sorted(data["categories"], key=lambda c: c["id"])
    label_map = {c["id"]: i for i, c in enumerate(cats)}
    log.info(
        "Label map dynamique : %d classes (ids %d→%d)",
        len(label_map),
        cats[0]["id"],
        cats[-1]["id"],
    )
    return label_map, len(label_map)


